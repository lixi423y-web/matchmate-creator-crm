import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {handoffSnapshot,directShippingPatch,directShippingLabel} from '../src/shipping-handoff.js';
import {shippingAddressText} from '../src/shipping-address.js';
globalThis.window={MATCHMATE_CONFIG:{}};
globalThis.location={search:'?demo=1&size=40'};
const api=await import('../src/data.js');
const rows=(await api.collaborationPage({pageSize:1000})).data;
const c=rows.find(r=>!r.shipments?.length);
assert.ok(c);const creatorBefore=structuredClone(await api.getOne('creators',c.creator_id));
await api.save('collaborations',{id:c.id,stage:'Confirmed — Awaiting Details'});
let context=await api.shippingHandoffContext(c.id);
const full='Full name: Synthetic Person\nStreet: 100 Example Road\nPostcode: TEST\nPhone: DEMO';
const address=await api.saveShippingHandoff({collaborationId:c.id,mode:'address',expected:handoffSnapshot(context),values:{address_snapshot:{full_address:full,source:'shipment'}}});
assert.equal(address.saved.address_snapshot.recipient_name,undefined);
assert.equal(shippingAddressText(address.saved.address_snapshot),full);
assert.equal(address.saved.status,'Draft');
context=await api.shippingHandoffContext(c.id);
await api.saveShippingHandoff({collaborationId:c.id,mode:'shipping-owner',expected:handoffSnapshot(context),values:{owner_id:'owner-ivy',owner_name:'Ivy'}});
const products=await api.related('collaboration_products','collaboration_id',c.id);
if(!products.length)await api.syncCollaborationProducts(c.id,[{product_id:'product-1',quantity:2}]);
context=await api.shippingHandoffContext(c.id);
await api.saveShippingHandoff({collaborationId:c.id,mode:'tracking',expected:handoffSnapshot(context),values:{carrier:'',tracking_number:'SYNTHETIC-001'}});
context=await api.shippingHandoffContext(c.id);
const sent=await api.saveShippingHandoff({collaborationId:c.id,mode:'direct-status',expected:handoffSnapshot(context),values:{status:'Shipped'}});
assert.equal(sent.saved.status,'Shipped');assert.ok(sent.saved.shipped_at);
assert.equal(sent.saved.tracking_number,'SYNTHETIC-001');assert.equal(sent.saved.carrier,null);
assert.equal((await api.getOne('collaborations',c.id)).stage,'In Fulfillment');
await assert.rejects(api.saveShippingHandoff({collaborationId:c.id,mode:'direct-status',expected:handoffSnapshot(context),values:{status:'Delivered'}}),/HANDOFF_CONFLICT/);
context=await api.shippingHandoffContext(c.id);
await api.saveShippingHandoff({collaborationId:c.id,mode:'tracking',expected:handoffSnapshot(context),values:{carrier:'',tracking_number:''}});
assert.equal((await api.getOne('shipments',sent.saved.id)).tracking_number,null);
await api.save('collaborations',{id:c.id,stage:'Published'});
context=await api.shippingHandoffContext(c.id);
await api.saveShippingHandoff({collaborationId:c.id,mode:'direct-status',expected:handoffSnapshot(context),values:{status:'Delivered'}});
assert.equal((await api.getOne('collaborations',c.id)).stage,'Published');
assert.deepEqual(await api.getOne('creators',c.creator_id),creatorBefore);
assert.throws(()=>directShippingPatch({status:'Shipped'},{status:'Pending'}),/earlier/);
assert.equal(directShippingLabel('Draft'),'Pending');assert.equal(directShippingLabel('Ready'),'Pending');assert.equal(directShippingLabel('Delivered'),'Delivered');
const selected=await api.collaborationPage({pageSize:1000,filters:{shipping_owner_id:'owner-ivy',shipping_status:'Delivered'}});
assert.ok(selected.data.some(r=>r.id===c.id));assert.ok(selected.data.every(r=>r.shipments.some(s=>s.owner_id==='owner-ivy'&&s.status==='Delivered')));
const app=readFileSync(new URL('../src/app.js',import.meta.url),'utf8'),ui=readFileSync(new URL('../src/shipping-handoff-ui.js',import.meta.url),'utf8');
const list=app.slice(app.indexOf('function renderCollaborations'),app.indexOf('function paginationPages'));
assert.ok(!list.includes('Hand over for shipping'));assert.ok(!list.includes('View shipment'));
assert.ok(list.includes('shipping-status-quick-edit'));assert.ok(list.includes("'direct-status'"));
const addressEditor=ui.slice(ui.indexOf("if(action==='address')"),ui.indexOf("}else if(action==='outreach-owner')"));
assert.ok(addressEditor.includes('rows="9"'));assert.ok(!addressEditor.includes('name="recipient_name"'));assert.ok(!addressEditor.includes('name="phone"'));
console.log('Simple shipping: direct Draft→Shipped, optional carrier/tracking, one-box recipient, date autofill, status sync, no stage regression, stale writes, filters and creator preservation passed.');
