import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const app=await readFile(new URL('../src/app.js',import.meta.url),'utf8');
const html=await readFile(new URL('../index.html',import.meta.url),'utf8');
const input={type:'password'};
let reads=0; Object.defineProperty(input,'value',{get(){reads++;throw new Error('toggle must not read password')}});
const button={attrs:{},setAttribute(name,value){this.attrs[name]=value}};
const nodes={'#loginPassword':input,'#toggleLoginPassword':button};
const context=vm.createContext({$:selector=>nodes[selector]});
const fn=app.split('\n').find(line=>line.startsWith('function setPasswordVisibility('));
assert.ok(fn);
vm.runInContext(fn,context);
vm.runInContext('setPasswordVisibility(true)',context);
assert.equal(input.type,'text');assert.equal(button.textContent,'隐藏');assert.equal(button.attrs['aria-pressed'],'true');
vm.runInContext('setPasswordVisibility(false)',context);
assert.equal(input.type,'password');assert.equal(button.textContent,'显示');assert.equal(button.attrs['aria-pressed'],'false');
assert.equal(reads,0);
assert.match(html,/id="toggleLoginPassword"[^>]*type="button"/);
assert.match(html,/id="loginPassword"[^>]*type="password"[^>]*autocomplete="current-password"/);
assert.match(app,/reset\(\);setPasswordVisibility\(false\);await openApp/);
assert.match(app,/value='';setPasswordVisibility\(false\);showLoginError/);
assert.ok(!app.includes("from'./followers.js'"));
console.log(JSON.stringify({defaultHidden:true,showHideWorks:true,neverReadsPassword:true,noSubmit:true,resetAfterLoginAndLogout:true,followersNotIncluded:true}));
