import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const app=readFileSync(new URL('../src/app.js',import.meta.url),'utf8');
const html=readFileSync(new URL('../index.html',import.meta.url),'utf8');
const ui=readFileSync(new URL('../src/shipping-handoff-ui.js',import.meta.url),'utf8');
const context=vm.createContext({});
for(const name of ['esc','attr','renderCollaborationTracking'])vm.runInContext(app.split('\n').find(l=>l.startsWith('function '+name+'(')),context);
const rows=[{id:'parcel-1',carrier:'UPS',tracking_number:'001234567890',tracking_url:'https://example.com/track'},{id:'parcel-2',tracking_number:'SECOND',tracking_url:'javascript:alert(1)'},{id:'old',tracking_number:'ARCHIVED',archived_at:'2026-01-01'},{id:'draft',tracking_number:null}];
const before=JSON.stringify(rows),rendered=context.renderCollaborationTracking(rows);
assert.ok(rendered.includes('001234567890'));assert.ok(rendered.includes('SECOND'));
assert.ok(rendered.includes('href="https://example.com/track"'));
assert.ok(!rendered.includes('javascript:'));assert.ok(!rendered.includes('ARCHIVED'));
assert.equal((rendered.match(/tracking-quick-edit/g)||[]).length,3);
assert.ok(rendered.includes('data-shipment-id="parcel-2"'));
assert.ok(context.renderCollaborationTracking([]).includes('No tracking yet'));
assert.ok(context.renderCollaborationTracking([{id:'x',tracking_number:'<unsafe>'}]).includes('&lt;unsafe&gt;'));
assert.equal(JSON.stringify(rows),before,'rendering never mutates shipping data');
assert.ok(!html.includes('data-collaboration-mode="shipping"'),'no separate Shipping handoff entry');
assert.ok(html.includes('Shipping &amp; tracking'));
assert.ok(ui.includes("let mode='records'"),'old saved shipping view returns to collaborations');
assert.ok(ui.includes("openShipment(collaborationId)"),'view shipment stays in collaboration details');
assert.ok(app.includes('renderCollaborationTracking(row.shipments)'));
console.log('Collaboration tracking: all active parcels, archived exclusion, safe links, edit/add, empty state, no mutations, single-page navigation passed.');
