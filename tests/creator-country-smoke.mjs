import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {SHIPPING_COUNTRIES} from '../src/shipping-countries.js';
assert.equal(SHIPPING_COUNTRIES.length,39);
assert.equal(new Set(SHIPPING_COUNTRIES.map(row=>row.code)).size,39);
assert.ok(!SHIPPING_COUNTRIES.some(row=>['ZA','BR','CN'].includes(row.code)));
const app=readFileSync(new URL('../src/app.js',import.meta.url),'utf8');
const context=vm.createContext({SHIPPING_COUNTRIES});
for(const name of ['esc','attr','field','selectField'])vm.runInContext(app.split('\n').find(line=>line.startsWith(`function ${name}(`)),context);
context.location='United States';
const html=vm.runInContext("selectField('location','Location',SHIPPING_COUNTRIES.map(row=>row.name),location,true)",context);
assert.equal((html.match(/<select /g)||[]).length,1);
assert.ok(html.includes('name="location"'));
assert.ok(html.includes('value="United States" selected'));
assert.equal((html.match(/<option /g)||[]).length,40);
context.location='New York, NY, United States';
const legacy=vm.runInContext("selectField('location','Location',SHIPPING_COUNTRIES.map(row=>row.name),location,true)",context);
assert.ok(legacy.includes('value="New York, NY, United States" selected'),'keep existing location until explicitly changed');
assert.ok(!app.includes('location_country'));
assert.ok(!app.includes('location_detail'));
assert.ok(!app.includes('creatorLocationFields'));
assert.ok(app.includes("selectField('location','Location',SHIPPING_COUNTRIES.map(row=>row.name),c.location,editing)"));
const quickAdd=app.split("function creatorProfileForm(c,editing){if(editing&&!c.id)return")[1].split(";return")[0];
assert.ok(!quickAdd.includes('SHIPPING_COUNTRIES'),'quick add is unchanged');
